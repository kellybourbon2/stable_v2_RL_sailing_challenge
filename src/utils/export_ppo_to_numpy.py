def _var_name(layer_key: str, suffix: str) -> str:
    """Convert 'wind_branch.0' + 'W' → '_wind_branch_0_W'."""
    return '_' + layer_key.replace('.', '_') + '_' + suffix


def _var_block(var_name: str, arr: np.ndarray) -> str:
    """Generate base64 decode + reshape block for one weight tensor."""
    shape = arr.shape
    enc   = _encode(arr)
    lines = enc.split('\n')
    quoted = '"' + ('"\n    "'.join(lines)) + '"'
    return (
        f"{var_name}_b64 = (\n    {quoted}\n)\n"
        f"{var_name} = np.frombuffer(base64.b64decode({var_name}_b64), dtype=np.float32)"
        f".reshape({shape})\n"
    )


