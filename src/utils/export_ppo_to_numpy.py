# ── Numpy conv2d (Conv2d + ReLU, no padding) ─────────────────────────────────

def _conv2d(x, W, b, stride):
    """
    x: (C_in, H, W)  W: (C_out, C_in, kH, kW)  b: (C_out,)
    Returns (C_out, H_out, W_out) after ReLU.
    Uses stride_tricks im2col — no Python loops over spatial dims.
    """
    x = np.ascontiguousarray(x, dtype=np.float32)
    C_in, H, Wi = x.shape
    C_out, _, kH, kW = W.shape
    Ho = (H  - kH) // stride + 1
    Wo = (Wi - kW) // stride + 1
    shape   = (Ho, Wo, C_in, kH, kW)
    strides = (x.strides[1] * stride, x.strides[2] * stride,
               x.strides[0], x.strides[1], x.strides[2])
    windows = np.lib.stride_tricks.as_strided(x, shape=shape, strides=strides)
    # (Ho*Wo, C_in*kH*kW) @ (C_out, C_in*kH*kW).T + b → (Ho*Wo, C_out)
    out = windows.reshape(Ho * Wo, -1) @ W.reshape(C_out, -1).T + b
    return np.maximum(0.0, out.reshape(Ho, Wo, C_out).transpose(2, 0, 1))


