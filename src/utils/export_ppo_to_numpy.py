def _encode(arr: np.ndarray) -> str:
    """Encode a numpy array as a base64 string of float32 bytes (80-char lines)."""
    b64 = base64.b64encode(arr.astype(np.float32).tobytes()).decode('ascii')
    lines = [b64[i:i+80] for i in range(0, len(b64), 80)]
    return '\n'.join(lines)


